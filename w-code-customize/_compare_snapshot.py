"""Compare the customized Horilla project against the original Horilla 2.0 source.

- Finds files that were modified or added in the project (hash comparison,
  CRLF/LF normalized).
- Copies each modified/added file into w-code-customize preserving its path.
- Removes stale snapshot copies that no longer differ from the original
  (and never stores secrets like `.env` or database files).
- Rewrites w-code-customize/CUSTOMIZE_INDEX.md with usage instructions and a
  grouped list of all custom files (this section is generated, edit the
  script to change the wording).
"""
import hashlib
import shutil
from pathlib import Path

PROJECT = Path(r"d:\vuthy.nop\2. Build Website\Web\horilla-hrms")
ORIGINAL = Path(r"C:\Users\Vuthy.Nop\AppData\Local\Temp\horilla-orig\horilla-hr-2.0")
DEST = PROJECT / "w-code-customize"

EXCLUDE_DIRS = {
    ".venv", ".venv-1", ".vscode", ".kilo", ".github", "__pycache__",
    "staticfiles", "w-code-customize", ".git", "node_modules", "media",
}
EXCLUDE_FILES = {
    "db.sqlite3", "TestDB.sqlite3", "probe.txt", "perm_baseline.json",
    "horilla-2.0.zip", "_layout_test.pdf", "_compare_snapshot.py",
    ".env",  # contains SECRET_KEY / DB_PASSWORD - never snapshot secrets
}
EXCLUDE_EXT = {".pyc", ".log", ".sqlite3", ".pdf"}


def normalize_bytes(p: Path) -> bytes:
    data = p.read_bytes()
    # Normalize CRLF / CR -> LF so a Windows checkout doesn't falsely differ
    # from the LF zip archive of the original source.
    try:
        text = data.decode("utf-8")
        return text.replace("\r\n", "\n").replace("\r", "\n").encode("utf-8")
    except UnicodeDecodeError:
        return data


def hash_file(p: Path) -> str:
    return hashlib.sha256(normalize_bytes(p)).hexdigest()


def collect(root: Path) -> dict:
    """Return {relpath: hash} for the source tree (text/bin source files)."""
    files = {}
    for p in sorted(root.rglob("*")):
        if not p.is_file():
            continue
        rel = p.relative_to(root)
        parts = set(rel.parts)
        if parts & EXCLUDE_DIRS:
            continue
        if p.name in EXCLUDE_FILES or p.suffix.lower() in EXCLUDE_EXT:
            continue
        if any(part == "__pycache__" for part in rel.parts):
            continue
        files[str(rel).replace("\\", "/")] = p
    return files


def main():
    proj_files = collect(PROJECT)
    orig_files = collect(ORIGINAL)

    added = sorted(set(proj_files) - set(orig_files))
    modified = []
    unchanged = 0
    for rel in sorted(set(proj_files) & set(orig_files)):
        if hash_file(proj_files[rel]) != hash_file(orig_files[rel]):
            modified.append(rel)
        else:
            unchanged += 1

    removed = sorted(set(orig_files) - set(proj_files))

    # Copy modified + added files into w-code-customize preserving paths
    copied = 0
    for rel in modified + added:
        src = PROJECT / rel
        dst = DEST / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, dst)
        copied += 1

    # Remove stale copies: files previously snapshotted but now identical to
    # the original (customization reverted) or deleted from the project.
    stale = 0
    for p in DEST.rglob("*"):
        if not p.is_file() or p.name in ("CUSTOMIZE_INDEX.md", "_compare_snapshot.py"):
            continue
        rel = str(p.relative_to(DEST)).replace("\\", "/")
        if rel not in modified and rel not in added:
            p.unlink()
            stale += 1
    # Drop directories that became empty (e.g. leftover 'in' folder)
    for p in sorted(DEST.rglob("*"), reverse=True):
        if p.is_dir() and not any(p.iterdir()):
            p.rmdir()

    # Build README grouped by top-level module (root-level files first)
    groups = {}
    for rel in modified:
        head, _, rest = rel.partition("/")
        key = "" if not rest else head
        groups.setdefault(key, {"M": [], "A": []})["M"].append(rel)
    for rel in added:
        head, _, rest = rel.partition("/")
        key = "" if not rest else head
        groups.setdefault(key, {"M": [], "A": []})["A"].append(rel)

    lines = []
    lines.append("# Customized Code Snapshot")
    lines.append("")
    lines.append("Generated by comparing this project against the original Horilla 2.0")
    lines.append("source (github.com/horilla/horilla-hr, branch `2.0`).")
    lines.append("")
    lines.append("Every file below differs from the original (modified) or does not exist")
    lines.append("in the original (added). The copy in this folder keeps the same relative")
    lines.append("path as the real file in the project, so after a system update you know")
    lines.append("exactly which files carry custom changes.")
    lines.append("")
    lines.append("How to use this folder")
    lines.append("----------------------")
    lines.append("1. `w-code-customize\\<path>` mirrors the real project path exactly.")
    lines.append("   Example: `w-code-customize\\payroll\\methods\\tax_calc.py` is the")
    lines.append("   customized copy of `payroll\\methods\\tax_calc.py` in the project root.")
    lines.append("2. After updating the Horilla system, check CUSTOMIZE_INDEX.md (this file)")
    lines.append("   first: every file listed here carries custom changes and must be")
    lines.append("   re-checked / re-applied to the updated code.")
    lines.append("3. To restore a customized file over a freshly updated one, copy it from")
    lines.append("   this folder back to the same relative path in the project root.")
    lines.append("4. `[ADDED]` files are brand new (did not exist in the original) - if a")
    lines.append("   system update does not include them, copy them over as-is.")
    lines.append("5. To refresh this snapshot after making more custom changes, run:")
    lines.append("")
    lines.append("   .venv\\Scripts\\python.exe _compare_snapshot.py")
    lines.append("")
    lines.append("   (run from the project root; edit ORIGINAL inside the script if the")
    lines.append("   baseline must change). `.env` and database files are never snapshotted.")
    lines.append("")
    lines.append("Important caveat")
    lines.append("----------------")
    lines.append("The project has no git history, so the baseline could not be pinned to")
    lines.append("the exact commit this fork started from. The comparison baseline is the")
    lines.append("*latest* `2.0` branch of github.com/horilla/horilla-hr (downloaded")
    lines.append("2026-09-19). Upstream has moved forward since the fork was created:")
    lines.append("")
    lines.append("- Files whose only difference is *upstream progress* also appear as")
    lines.append("  [MODIFIED] here. Treat this list as \"every file that differs from")
    lines.append("  upstream 2.0\", which is the safe superset when re-applying custom code.")
    lines.append("- Files listed under \"missing from this project\" are new upstream files")
    lines.append("  that this fork does not have yet - useful to know when planning an")
    lines.append("  update.")
    lines.append("- Files with known customizations (see SALARY_TAX_TEST_GUIDE.md and")
    lines.append("  PAYROLL_TAX_TEST_WORKFLOW.md, e.g. `payroll/methods/tax_calc.py`,")
    lines.append("  `payroll/forms/tax_forms.py`, the PayrollSettings `usd_to_khr_rate`")
    lines.append("  field and related migrations/templates) are definitely custom work")
    lines.append("  and must never be overwritten blindly by an update.")
    lines.append("")
    lines.append(f"- **{len(modified)}** modified file(s)")
    lines.append(f"- **{len(added)}** added file(s) (new, not in original)")
    lines.append(f"- **{unchanged}** file(s) unchanged vs. original")
    lines.append(f"- **{stale}** stale snapshot file(s) removed on this run")
    lines.append("")
    if removed:
        lines.append(f"> Note: {len(removed)} file(s) present in the original are absent in this")
        lines.append("> project (deleted or never copied upstream). They are listed at the end.")
        lines.append("")
    lines.append("## File list by module")
    lines.append("")
    for grp in sorted(groups):
        title = "(project root)" if grp == "" else f"`{grp}/`"
        lines.append(f"### {title}")
        lines.append("")
        for rel in groups[grp]["M"]:
            lines.append(f"- [MODIFIED] `{rel}`")
        for rel in groups[grp]["A"]:
            lines.append(f"- [ADDED] `{rel}`")
        lines.append("")
    if removed:
        lines.append("## Files missing from this project (present in original)")
        lines.append("")
        for rel in removed:
            lines.append(f"- [MISSING] `{rel}`")
        lines.append("")

    # NOTE: the project's root README.md is itself a customized file, so it is
    # snapshotted as w-code-customize/README.md. The generated index therefore
    # uses its own name to avoid overwriting it.
    (DEST / "CUSTOMIZE_INDEX.md").write_text("\n".join(lines), encoding="utf-8")

    print(
        f"modified={len(modified)} added={len(added)} unchanged={unchanged} "
        f"removed={len(removed)} copied={copied} stale_removed={stale}"
    )
    print("index written to", DEST / "CUSTOMIZE_INDEX.md")


if __name__ == "__main__":
    main()
