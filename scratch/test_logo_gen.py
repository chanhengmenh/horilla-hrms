import base64
from xhtml2pdf import pisa
from io import BytesIO

with open('scratch/extracted_img_7_Image30.jpg', 'rb') as f:
    img_b64 = base64.b64encode(f.read()).decode('utf-8')

html = f'''<!DOCTYPE html>
<html>
<head>
<style>
@page {{
    size: letter portrait;
    margin: 0.5in;
}}
</style>
</head>
<body>
<img src="data:image/jpeg;base64,{img_b64}" width="140" />
<p>Hello PDF</p>
</body>
</html>'''

out = BytesIO()
pisa_status = pisa.CreatePDF(html, dest=out)
print('PDF error status:', pisa_status.err)
print('Generated bytes:', len(out.getvalue()))
with open('scratch/test_logo.pdf', 'wb') as f:
    f.write(out.getvalue())
